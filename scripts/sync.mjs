// Builds papers.json and README.md from each paper's paper.json. Run: node scripts/sync.mjs <guides-dir>
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const guides = process.argv[2];
if (!guides) throw new Error("usage: node scripts/sync.mjs <guides-dir>");
const root = join(guides, "papers");
const papers = readdirSync(root)
  .filter((d) => /^\d{4}-\d{3}-/.test(d) && existsSync(join(root, d, "paper.json")))
  .map((d) => JSON.parse(readFileSync(join(root, d, "paper.json"), "utf8")))
  .map((m) => ({
    id: m.id,
    title: m.title,
    subtitle: m.subtitle,
    version: m.version,
    status: m.status,
    date: m.date_iso,
    url: m.url,
    repo: m.artifacts?.repo ?? m.repo,
    tag: m.artifacts?.tag ?? null,
    doi: m.artifacts?.doi ?? m.doi ?? null,
    pdf: m.archive_url ?? null,
    license: m.license,
    review: m.review?.status ?? "none",
  }))
  .sort((a, b) => a.id.localeCompare(b.id));

writeFileSync("papers.json", JSON.stringify(papers, null, 2) + "\n");

const cell = (v, text) => (v ? `[${text}](${v})` : "pending");
const rows = papers.map((p) =>
  `| ${p.id} | ${p.title} | ${p.version} (${p.status}) | ${cell(p.pdf, "PDF")} | ${cell(p.doi && `https://doi.org/${p.doi}`, "DOI")} | ${cell(p.repo, p.tag ?? "repo")} |`,
);
writeFileSync(
  "README.md",
  `# GLINR whitepapers

[![Code license: MIT](https://img.shields.io/badge/code-MIT-blue)](LICENSE)
[![Reports](https://img.shields.io/badge/reports-${papers.length}-orange)](papers.json)
[![Publisher](https://img.shields.io/badge/publisher-GLINR%20Studios-black)](https://glinr.com)

One index for every GLINR Studios whitepaper: the PDF, its DOI and the repository with the scripts and raw results behind it.

| Report | Title | Version | Paper | DOI | Evidence |
| --- | --- | --- | --- | --- | --- |
${rows.join("\n")}

Reports are independent technical write-ups, not externally reviewed unless a paper says otherwise. Each evidence repository is tagged per paper version.

## Find a report

- Each row links the paper PDF (a release asset), its Zenodo DOI and the repository with the scripts and raw results.
- \`papers.json\` is the same data for tools: id, title, version, status, date, PDF, DOI, repo, tag, license and review status.
- Evidence repositories carry \`CITATION.cff\`, so GitHub's "Cite this repository" button works on each.

This file and \`papers.json\` are generated by \`node scripts/sync.mjs <guides-dir>\`. Do not edit them by hand.
`,
);
